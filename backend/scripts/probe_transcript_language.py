"""Why does a Tamil speaker's words come out written in Telugu?

The transcription hint is sent as a bare `ta`. Proper BCP-47 for Tamil as
spoken in India is `ta-IN`, and if the server wants the region-qualified form
a bare code may simply be ignored - leaving Gemini to guess the script from
8 kHz phone audio, which is how a Tamil speaker ends up written out in Telugu.

This settles it with real speech rather than argument: the same Tamil audio is
sent three times, with no hint, with `ta`, and with `ta-IN`, and the three
transcriptions are printed side by side.

    cd backend
    ..\\.venv\\Scripts\\python.exe scripts/probe_transcript_language.py
    ..\\.venv\\Scripts\\python.exe scripts/probe_transcript_language.py --lang hi

The clip is the waiting-room greeting generated by `make_greetings.py`, which
is genuine synthesised speech in that language.
"""

from __future__ import annotations

import asyncio
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.config import get_settings                     # noqa: E402
from app.services import gemini_service                 # noqa: E402
from app.utils import audio                             # noqa: E402

FRAME_BYTES = 160                 # 20 ms of µ-law, one Twilio frame
SETTLE_S = 12.0                   # how long to wait for the model to finish

REGION = {"ta": "ta-IN", "hi": "hi-IN", "te": "te-IN", "en": "en-IN",
          "kn": "kn-IN", "ml": "ml-IN", "bn": "bn-IN", "gu": "gu-IN",
          "mr": "mr-IN", "es": "es-ES"}


async def transcribe(lang: str, hint: str | None, clip: bytes) -> str:
    """Send the clip with one hint and return what came back as 'heard'."""
    heard: list[str] = []

    async def on_audio(_payload: str) -> None:
        pass

    async def on_transcript(kind: str, text: str) -> None:
        if kind == "in" and text:
            heard.append(text)

    session = gemini_service.GeminiTranslateSession(
        get_settings(),
        source_language=lang,
        target_language="en" if lang != "en" else "ta",
        on_audio=on_audio,
        on_transcript=on_transcript,
        label=f"probe/{hint or 'none'}",
    )
    # The hint is derived from source_language; override it for the probe.
    type(session).source_hint = property(lambda self, h=hint: h)

    await session.connect()
    try:
        for i in range(0, len(clip) - FRAME_BYTES, FRAME_BYTES):
            await session.append_audio(
                audio.b64_encode(clip[i:i + FRAME_BYTES]))
            await asyncio.sleep(0.004)          # roughly real time, sped up
        await asyncio.sleep(SETTLE_S)
    finally:
        await session.close()
    return " ".join(heard).strip()


async def main(lang: str) -> None:
    clip_path = (Path(__file__).resolve().parent.parent
                 / "app" / "data" / "greetings" / f"{lang}.ulaw")
    if not clip_path.exists():
        raise SystemExit(f"no speech clip for {lang!r}: {clip_path}")
    clip = clip_path.read_bytes()
    print(f"{lang}: {len(clip) / 8000:.1f}s of real speech\n")

    for label, hint in (("no hint at all", None),
                        ("bare code (what we send now)", lang),
                        (f"region-qualified", REGION.get(lang, lang))):
        try:
            got = await transcribe(lang, hint, clip)
        except Exception as exc:                        # noqa: BLE001
            got = f"<failed: {type(exc).__name__}: {str(exc)[:80]}>"
        print(f"  {label:32} hint={str(hint):8} -> {got[:90] or '<nothing>'}")


if __name__ == "__main__":
    argv = sys.argv[1:]
    language = argv[argv.index("--lang") + 1] if "--lang" in argv else "ta"
    asyncio.run(main(language))
