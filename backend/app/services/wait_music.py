"""Music played to the person who answers, until the first translation lands.

Nothing can be translated until enough of a sentence has been said, so the
person who answered hears a few seconds of nothing after they pick up. Real
calls have ended with "Hello? Am I audible?" and a hang-up.

Music says "wait, something is coming" in every language at once. It starts
when their stream opens and stops the instant the first translated voice
reaches them; after that the call is silent between turns, as it always was.
Their own speaking does NOT stop it - only our translated audio does, because
"hello?" into a silent line is exactly the person this exists to reassure.

The loop is generated by `scripts/make_hold_music.py` and committed, so a live
call never waits on anything to produce it. If the file is missing, no music
plays and calls are unaffected: that is the safe direction, and it is why a
missing file needs no handling anywhere else.
"""

from __future__ import annotations

import asyncio
import logging
from pathlib import Path

from app.utils import audio

log = logging.getLogger("app.wait_music")

MUSIC_FILE = Path(__file__).resolve().parent.parent / "data" / "music" / "wait.ulaw"

FRAME_MS = 20                       # one Twilio media frame
FRAME_BYTES = 8 * FRAME_MS          # µ-law is one byte per sample at 8 kHz
LEAD_S = 1.5                        # keep this much queued ahead at Twilio
TOP_UP_S = 0.2                      # how often to check the queue

_frames: list[str] | None = None


def frames() -> list[str]:
    """The loop as base64 media frames, read once and kept.

    An unreadable or truncated file yields no frames, which silently disables
    the music rather than failing a call.
    """
    global _frames
    if _frames is not None:
        return _frames

    try:
        raw = MUSIC_FILE.read_bytes()
    except OSError as exc:
        log.warning("wait_music_unavailable", extra={"reason": str(exc)[:120]})
        _frames = []
        return _frames

    whole = len(raw) // FRAME_BYTES          # a part-frame at the end would click
    _frames = [
        audio.b64_encode(raw[i * FRAME_BYTES:(i + 1) * FRAME_BYTES])
        for i in range(whole)
    ]
    log.info("wait_music_loaded",
             extra={"frames": len(_frames),
                    "seconds": round(whole * FRAME_MS / 1000, 1)})
    return _frames


def available() -> bool:
    return bool(frames())


async def play_until_cancelled(write_frame, backlog_s) -> None:
    """Loop the music into one leg until this task is cancelled.

    Rather than pacing frame by frame, this keeps roughly `LEAD_S` of audio
    queued at Twilio and tops it up. Cancelling therefore leaves at most that
    much still to play, which the caller drops with a clear.
    """
    loop = frames()
    if not loop:
        return

    index = 0
    while True:
        while backlog_s() < LEAD_S:
            if not await write_frame(loop[index % len(loop)]):
                return                      # the leg went away
            index += 1
        await asyncio.sleep(TOP_UP_S)
